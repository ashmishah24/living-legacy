import { readFileSync, writeFileSync } from 'node:fs';
const source = JSON.parse(readFileSync(new URL('../docs/design/tokens.json', import.meta.url), 'utf8'));
const flat = new Map();
function walk(node, path = []) { for (const [key, value] of Object.entries(node)) { if (key.startsWith('$')) continue; if ('$value' in value) flat.set([...path, key].join('.'), value); else walk(value, [...path, key]); } }
walk(source);
function resolve(name, seen = new Set()) {
  if (seen.has(name)) throw new Error(`Circular token: ${name}`);
  seen.add(name); const token = flat.get(name); if (!token) throw new Error(`Missing token: ${name}`);
  const value = token.$value;
  if (typeof value === 'string' && value.startsWith('{')) return resolve(value.slice(1, -1), seen);
  if (token.$type === 'color') {
    const channels = value.alpha === undefined || value.alpha === 1 ? value.components : [...value.components, value.alpha];
    return '#' + channels.map(n => Math.round(n * 255).toString(16).padStart(2, '0')).join('');
  }
  if (token.$type === 'dimension') return `${value.value}${value.unit}`;
  if (token.$type === 'number') return String(value);
  if (token.$type === 'fontFamily') return value.map(name => ['serif', 'sans-serif', 'monospace', 'system-ui'].includes(name) ? name : JSON.stringify(name)).join(', ');
  throw new Error(`Unsupported token type: ${token.$type}`);
}
const css = '/* Generated by pnpm tokens:generate; edit docs/design/tokens.json. */\n:root {\n' + [...flat.keys()].filter(k => !k.startsWith('palette.')).map(k => `  --${k.replaceAll('.', '-')}: ${resolve(k)};`).join('\n') + '\n}\n';
const target = new URL('../apps/web/app/tokens.css', import.meta.url);
if (process.argv.includes('--check')) { if (readFileSync(target, 'utf8') !== css) throw new Error('Token CSS is stale; run pnpm tokens:generate'); console.log('Design token CSS matches source.'); }
else writeFileSync(target, css);
